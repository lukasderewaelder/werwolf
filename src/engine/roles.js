export const RM = Object.fromEntries(ROLES.map((r) => [r.id, r]));

/** Rollen, die als Werwolf zählen (Wolfshund, Wildes Kind und Infizierte kommen im Spielzustand dazu). */
export const WOLF_IDS = ['wolf', 'urwolf', 'bigwolf', 'whitewolf'];

/** Rollen, die der Gaukler in der Mitte angeboten bekommen darf (keine Wölfe). */
export const ACTOR_POOL = ['seer', 'fox', 'guard', 'raven', 'hunter', 'idiot', 'scapegoat', 'bear', 'knight', 'elder', 'girl'];

export const CAMP_LABEL = { village: 'Dorfbewohner', wolf: 'Werwölfe', twofold: 'Zweideutige', solo: 'Einzelgänger' };

export const roleName = (id) => RM[id]?.name ?? 'Unbekannt';
export const roleShort = (id) => RM[id]?.short ?? RM[id]?.name ?? 'Unbekannt';

/** Sucht Rollen nach Name, Kurzname oder altem Namen (ohne Groß-/Kleinschreibung). */
export function findRoles(query) {
  const q = query.trim().toLowerCase();
  if (!q) return ROLES;
  return ROLES.filter((r) => [r.name, r.short, ...(r.alt ?? [])].some((n) => n?.toLowerCase().includes(q)));
}

/** Vorschlag für die Kartenverteilung nach Spielerzahl (Rest wird mit Dorfbewohnern aufgefüllt). */
export function recommendCounts(n) {
  const c = { wolf: n < 6 ? 1 : n < 12 ? 2 : n < 18 ? 3 : n < 25 ? 4 : 5, seer: 1 };
  if (n >= 5) c.witch = 1;
  if (n >= 6) c.hunter = 1;
  if (n >= 8) c.cupid = 1;
  if (n >= 10) c.girl = 1;
  if (n >= 14) c.guard = 1;
  if (n >= 18) c.idiot = 1;
  return fillVillagers(c, n);
}

/** Benötigte Kartenzahl: Spieler plus zwei Mittelkarten beim Dieb. */
export const requiredCards = (counts, n) => n + ((counts.thief ?? 0) > 0 ? 2 : 0);

export function fillVillagers(counts, n) {
  const rest = Object.entries(counts).filter(([k]) => k !== 'villager').reduce((s, [, v]) => s + (v || 0), 0);
  return { ...counts, villager: Math.max(0, requiredCards(counts, n) - rest) };
}

/** Rollen mit camp 'wolf' sowie der Weiße Werwolf zählen als Werwölfe. */
export const isWolfRole = (id) => RM[id]?.camp === 'wolf' || id === 'whitewolf';

/** Eigene Rollen (Name, Lager village|wolf, optionaler Aufruf) in die Rollentabelle eintragen. Ersetzt frühere Einträge gleicher Kennung. */
export function registerRoles(list = []) {
  for (const c of list) {
    const def = {
      id: c.id, name: c.name, set: 'eigene', camp: c.camp === 'wolf' ? 'wolf' : 'village', color: c.color || (c.camp === 'wolf' ? '#8a2a2a' : '#4a5f8f'),
      sub: c.sub || 'Eigene Rolle', desc: c.desc || '', say: c.say || '', custom: true,
      ...(c.wake && c.wake !== 'none' ? { night: { when: c.wake === 'first' ? 'first' : 'every', order: c.after ? 260 : 115, act: null } } : {}),
    };
    const i = ROLES.findIndex((x) => x.id === c.id);
    if (i >= 0) ROLES[i] = def; else ROLES.push(def);
    RM[c.id] = def;
  }
}
